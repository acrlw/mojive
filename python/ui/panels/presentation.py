"""Optional property presentation; panels retain their data and command ownership."""

from typing import Protocol


class PropertyPresentation(Protocol):
    def section(self, label: str, flags: int = 0) -> bool: ...
    def begin_table(self, table_id: str) -> bool: ...
    def row(self, label: str, *, minimum: float = 96, rail: bool = False) -> None: ...
    def numeric(
        self, item_id: str, value: float, speed: float, low: float, high: float, fmt: str
    ): ...
    def numbers(self, item_id: str, values, speed: float, low: float, high: float, fmt: str): ...
    def color(self, item_id: str, values): ...
    def labeled(self, label: str, value) -> None: ...
    def toggle(self, key: str, label: str, value: bool) -> bool: ...
    def segmented(self, item_id: str, labels, selected: int, *, icons=None) -> int: ...
    def value_rail(self, item_id: str, value: float, bounds, **options): ...
    def toggles(self, items): ...
    def plot_height(self, count: int) -> float: ...
    def checkbox(self, key: str, value: bool) -> tuple[bool, bool]: ...
