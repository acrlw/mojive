"""Optional property presentation; panels retain their data and command ownership."""

from typing import Protocol

from imgui_bundle import imgui


class PropertyPresentation(Protocol):
    def tooltip(self, text: str, *, hovered: bool = False) -> None: ...
    def section(self, label: str, flags: int = 0) -> bool: ...
    def begin_table(self, table_id: str) -> bool: ...
    def end_table(self) -> None: ...
    def combo(self, key: str, index: int, labels, flags: int = 0, *, preview=None): ...
    def begin_combo(self, key: str, preview: str, flags: int = 0) -> bool: ...
    def input_text(self, key: str, value: str, flags: int = 0): ...
    def button(self, label: str, size=None) -> bool: ...
    def row(
        self,
        label: str,
        *,
        minimum: float = 96,
        rail: bool = False,
        control_part: str = "input_number",
    ) -> None: ...
    def numeric(
        self, item_id: str, value: float, speed: float, low: float, high: float, fmt: str
    ): ...
    def numbers(self, item_id: str, values, speed: float, low: float, high: float, fmt: str): ...
    def color(self, item_id: str, values): ...
    def labeled(self, label: str, value) -> None: ...
    def toggle(self, key: str, label: str, value: bool) -> bool: ...
    def segmented(self, item_id: str, labels, selected: int, *, icons=None) -> int: ...
    def value_rail(self, item_id: str, value: float, bounds, **options): ...
    def toggles(self, items): ...
    def plot_height(self, count: int) -> float: ...
    def numeric_text_style(self, size_scale: float = 1.0): ...
    def multi_select(self, key: str, labels, values): ...
    def action_menu(self, key: str, label: str, actions) -> int | None: ...
    def choice_height(self) -> float: ...
    def checkbox(self, key: str, value: bool) -> tuple[bool, bool]: ...


def property_tooltip(presentation, text: str, *, hovered: bool = False) -> None:
    """Let an optional presenter own help typography; retain standalone native hints."""
    tooltip = getattr(presentation, "tooltip", None)
    if tooltip is not None:
        tooltip(text, hovered=hovered)
    elif hovered:
        imgui.set_tooltip(text)
    else:
        imgui.set_item_tooltip(text)
